function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    const stat = statSync(full)
    if (stat.isDirectory()) {
      if (name === 'node_modules' || name === 'dist' || name === 'dist-asset') continue
      walk(full, out)
      continue
    }
    if (sourceExtensions.has(extname(name))) out.push(full)
  }
  return out
}

function collectChars() {
  const chars = new Set()
  const addText = (text) => {
    for (const ch of text.normalize('NFC')) {
      const cp = ch.codePointAt(0)
      if (!cp) continue
      if (cp <= 0x7f) continue
      if (/\s/.test(ch)) continue
      chars.add(ch)
    }
  }
  addText(commonBusinessText)
  for (const file of walk(sourceRoot)) {
    addText(readFileSync(file, 'utf8'))
  }
  return Array.from(chars).sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
}

function unicodeRanges(chars) {
  const points = Array.from(new Set(chars.map((ch) => ch.codePointAt(0)))).sort((a, b) => a - b)
  const ranges = []
  let start = points[0]
  let end = points[0]
  for (let i = 1; i < points.length; i += 1) {
    const cp = points[i]
    if (cp === end + 1) {
      end = cp
      continue
    }
    ranges.push([start, end])
    start = cp
    end = cp
  }
  if (start !== undefined) ranges.push([start, end])
  return ranges
    .map(([a, b]) => (a === b ? `U+${a.toString(16).toUpperCase()}` : `U+${a.toString(16).toUpperCase()}-${b.toString(16).toUpperCase()}`))
    .join(', ')
}

